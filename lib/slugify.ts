/**
 * Приводит строку к url-safe слагу: нижний регистр, диакритика убирается
 * через разложение NFD, всё, кроме [a-z0-9], становится дефисом,
 * повторные дефисы схлопываются, дефисы по краям обрезаются.
 *
 * Буквы без канонического разложения в NFD (например, ß, ø, ł, æ) не
 * транслитерируются — они превращаются в дефис как любой другой
 * недопустимый символ. См. tests/unit/slugify.test.ts.
 */
export function slugify(input: string): string {
  return input
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
