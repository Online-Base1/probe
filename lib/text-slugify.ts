/**
 * Приводит строку к url-safe слагу без транслитерации: нижний регистр,
 * каждый символ, не входящий в [a-z0-9] (включая не-ASCII буквы), становится
 * дефисом, повторные дефисы схлопываются, дефисы по краям обрезаются.
 *
 * В отличие от lib/slugify.ts, здесь не-ASCII буквы не раскладываются через
 * NFD и не транслитерируются — они всегда трактуются как разделители.
 */
export function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
